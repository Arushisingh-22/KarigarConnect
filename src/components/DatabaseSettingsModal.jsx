import React, { useState } from 'react';
import { X, Database, Key, Globe, CheckCircle2, AlertCircle, Copy, Check, Terminal } from 'lucide-react';
import { getSupabaseConfig, saveSupabaseConfig, clearSupabaseConfig, testConnection, isUnsafeSupabaseKey } from '../lib/supabase';
import { useLanguage } from '../i18n';

function isValidProjectUrl(value) {
  try {
    const url = new URL(value);
    return url.protocol === 'https:'
      || (url.protocol === 'http:' && ['localhost', '127.0.0.1'].includes(url.hostname));
  } catch {
    return false;
  }
}

export default function DatabaseSettingsModal({ isOpen, onClose, onConfigSaved }) {
  const { t } = useLanguage();

  const [url, setUrl] = useState(() => getSupabaseConfig().url);
  const [key, setKey] = useState(() => getSupabaseConfig().key);
  const [isTesting, setIsTesting] = useState(false);
  const [testResult, setTestResult] = useState(null);
  const [copiedSql, setCopiedSql] = useState(false);
  const [copyError, setCopyError] = useState('');

  if (!isOpen) return null;

  const handleTest = async () => {
    const trimmedUrl = url.trim();
    const trimmedKey = key.trim();
    if (!trimmedUrl || !trimmedKey) {
      setTestResult({ success: false, message: t('Please provide both Supabase URL and Publishable Key.') });
      return;
    }
    if (isUnsafeSupabaseKey(trimmedKey)) {
      setTestResult({ success: false, message: t('Secret keys cannot be used in the browser. Enter a publishable or anon key.') });
      return;
    }
    if (!isValidProjectUrl(trimmedUrl)) {
      setTestResult({ success: false, message: t('Enter a valid HTTPS Supabase project URL.') });
      return;
    }

    setIsTesting(true);
    setTestResult(null);
    try {
      const res = await testConnection(trimmedUrl, trimmedKey);
      setTestResult(res);
    } catch (error) {
      setTestResult({
        success: false,
        message: error instanceof Error ? error.message : t('Connection failed')
      });
    } finally {
      setIsTesting(false);
    }
  };

  const handleSave = () => {
    const trimmedUrl = url.trim();
    const trimmedKey = key.trim();
    if (!trimmedUrl || !trimmedKey) {
      setTestResult({ success: false, message: t('Please provide both Supabase URL and Publishable Key.') });
      return;
    }
    if (isUnsafeSupabaseKey(trimmedKey)) {
      setTestResult({ success: false, message: t('Secret keys cannot be used in the browser. Enter a publishable or anon key.') });
      return;
    }
    if (!isValidProjectUrl(trimmedUrl)) {
      setTestResult({ success: false, message: t('Enter a valid HTTPS Supabase project URL.') });
      return;
    }
    try {
      saveSupabaseConfig(trimmedUrl, trimmedKey);
      if (onConfigSaved) onConfigSaved();
      onClose();
    } catch (error) {
      setTestResult({
        success: false,
        message: error instanceof Error ? error.message : t('Unable to save database settings.')
      });
    }
  };

  const handleClear = () => {
    try {
      clearSupabaseConfig();
      setUrl('');
      setKey('');
      setTestResult(null);
      if (onConfigSaved) onConfigSaved();
    } catch (error) {
      setTestResult({
        success: false,
        message: error instanceof Error ? error.message : t('Unable to clear saved settings.')
      });
    }
  };

  const sqlCode = `-- Create the artisans table in Supabase SQL Editor
CREATE TABLE IF NOT EXISTS artisans (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  craft TEXT NOT NULL,
  village TEXT NOT NULL,
  loan_amount NUMERIC NOT NULL,
  amount_raised NUMERIC DEFAULT 0,
  story TEXT NOT NULL,
  photo_url TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW()
);`;

  const copySql = async () => {
    setCopyError('');
    try {
      await navigator.clipboard.writeText(sqlCode);
      setCopiedSql(true);
      setTimeout(() => setCopiedSql(false), 2000);
    } catch (error) {
      setCopyError(error instanceof Error ? error.message : t('Unable to copy SQL.'));
    }
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-stone-900/60 backdrop-blur-xs">
      <div className="bg-white rounded-2xl max-w-xl w-full max-h-[90vh] overflow-y-auto shadow-2xl border border-stone-200 animate-in fade-in zoom-in-95 duration-200">
        
        {/* Header */}
        <div className="flex items-center justify-between p-5 border-b border-stone-100 bg-amber-50/50">
          <div className="flex items-center gap-2.5">
            <div className="w-8 h-8 rounded-lg bg-amber-700 text-white flex items-center justify-center">
              <Database className="w-4 h-4" />
            </div>
            <div>
              <h3 className="font-bold text-lg text-stone-900">{t('Supabase Connection Settings')}</h3>
              <p className="text-xs text-stone-500">{t('Connect your cloud database to sync live data')}</p>
            </div>
          </div>
          <button
            onClick={onClose}
            className="p-1.5 text-stone-400 hover:text-stone-700 rounded-lg hover:bg-stone-100 transition-colors"
            aria-label={t('Close')}
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* Body */}
        <div className="p-6 space-y-5">
          
          {/* Inputs */}
          <div className="space-y-4">
            <div>
              <label htmlFor="supabase-project-url" className="block text-xs font-bold uppercase tracking-wider text-stone-700 mb-1 flex items-center gap-1.5">
                <Globe className="w-3.5 h-3.5 text-stone-500" />
                {t('Project URL')}
              </label>
              <input
                id="supabase-project-url"
                type="url"
                placeholder="https://your-project-id.supabase.co"
                value={url}
                onChange={(e) => {
                  setUrl(e.target.value);
                  setTestResult(null);
                }}
                className="w-full px-3.5 py-2 text-sm bg-stone-50 border border-stone-200 rounded-xl focus:bg-white focus:outline-none focus:ring-2 focus:ring-amber-700 font-mono text-xs"
              />
            </div>

            <div>
              <label htmlFor="supabase-publishable-key" className="block text-xs font-bold uppercase tracking-wider text-stone-700 mb-1 flex items-center gap-1.5">
                <Key className="w-3.5 h-3.5 text-stone-500" />
                {t('Publishable / Anon API Key')}
              </label>
              <input
                id="supabase-publishable-key"
                type="password"
                placeholder="sb_publishable_... or eyJhbGci..."
                value={key}
                onChange={(e) => {
                  setKey(e.target.value);
                  setTestResult(null);
                }}
                className="w-full px-3.5 py-2 text-sm bg-stone-50 border border-stone-200 rounded-xl focus:bg-white focus:outline-none focus:ring-2 focus:ring-amber-700 font-mono text-xs"
              />
              <p className="text-xs text-stone-400 mt-1">
                {t("Use a publishable or anon key only. It is stored in browser local storage; never enter a service-role or secret key.")}
              </p>
            </div>
          </div>

          {/* Test Connection Button */}
          <div className="flex items-center gap-3">
            <button
              type="button"
              onClick={handleTest}
              disabled={isTesting}
              className="px-4 py-2 bg-stone-100 hover:bg-stone-200 text-stone-800 text-xs font-bold rounded-xl transition-colors disabled:opacity-50"
            >
              {isTesting ? t('Testing connection...') : t('Test Connection')}
            </button>
            {(url || key || localStorage.getItem('artisan_supabase_url') || localStorage.getItem('artisan_supabase_key')) && (
              <button
                type="button"
                onClick={handleClear}
                className="text-xs text-stone-500 hover:text-red-600 underline"
              >
                {t('Clear Saved Keys')}
              </button>
            )}
          </div>

          {copyError && (
            <p role="alert" className="text-xs text-red-700 bg-red-50 border border-red-200 rounded-lg p-3">
              {copyError}
            </p>
          )}

          {/* Test Result Message */}
          {testResult && (
            <div
              role={testResult.success ? 'status' : 'alert'}
              className={`p-3.5 rounded-xl border text-xs flex items-start gap-2.5 ${
                testResult.success
                  ? 'bg-emerald-50 border-emerald-200 text-emerald-800'
                  : 'bg-red-50 border-red-200 text-red-800'
              }`}
            >
              {testResult.success ? (
                <CheckCircle2 className="w-4 h-4 text-emerald-600 shrink-0 mt-0.5" />
              ) : (
                <AlertCircle className="w-4 h-4 text-red-600 shrink-0 mt-0.5" />
              )}
              <div>
                <p className="font-bold">{testResult.success ? t('Success!') : t('Connection Error')}</p>
                <p>{t(testResult.message)}</p>
              </div>
            </div>
          )}

          {/* Supabase SQL Helper Box */}
          <div className="border border-stone-200 rounded-xl overflow-hidden bg-stone-900 text-stone-100 text-xs">
            <div className="bg-stone-800 px-3.5 py-2 flex items-center justify-between border-b border-stone-700">
              <span className="font-mono text-stone-300 flex items-center gap-1.5">
                <Terminal className="w-3.5 h-3.5" />
                {t('Quick SQL for the Supabase artisans table')}
              </span>
              <button
                type="button"
                onClick={copySql}
                className="inline-flex items-center gap-1 px-2 py-0.5 rounded bg-stone-700 hover:bg-stone-600 text-stone-200 text-[11px]"
              >
                {copiedSql ? <Check className="w-3 h-3 text-emerald-400" /> : <Copy className="w-3 h-3" />}
                <span>{copiedSql ? t('Copied!') : t('Copy SQL')}</span>
              </button>
            </div>
            <pre className="p-3 font-mono text-[11px] overflow-x-auto text-amber-200/90 leading-relaxed">
              {sqlCode}
            </pre>
          </div>

        </div>

        {/* Footer */}
        <div className="flex items-center justify-end gap-3 p-5 border-t border-stone-100 bg-stone-50">
          <button
            type="button"
            onClick={onClose}
            className="px-4 py-2 text-sm font-semibold text-stone-600 hover:text-stone-800"
          >
            {t('Cancel')}
          </button>
          <button
            type="button"
            onClick={handleSave}
            className="px-5 py-2 bg-amber-700 hover:bg-amber-800 text-white rounded-xl font-bold text-sm shadow-xs transition-all"
          >
            {t('Save & Connect')}
          </button>
        </div>

      </div>
    </div>
  );
}
