const LanguageContext = createContext(null);

export function LanguageProvider({ children }) {
  const [language, setLanguage] = useState(() => {
    const savedLanguage = window.localStorage.getItem('karigarconnect-language');
    return savedLanguage === 'hi' ? 'hi' : 'en';
  });

  useEffect(() => {
    window.localStorage.setItem('karigarconnect-language', language);
    document.documentElement.lang = language;
    document.title = language === 'hi' ? 'कारीगरकनेक्ट | कारीगर समुदाय सहयोग' : 'KarigarConnect | Artisan Community Support';
  }, [language]);

  const value = useMemo(() => ({
    language,
    setLanguage,
    t: (key) => translations[language][key] ?? key
  }), [language]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error('useLanguage must be used within a LanguageProvider');
  }
  return context;
}
